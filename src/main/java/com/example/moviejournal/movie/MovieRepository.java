package com.example.moviejournal.movie;

import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Optional;

/**
 * Every query filters on user_id, so a user can never read or change another user's rows.
 */
@Repository
public class MovieRepository {
    private final JdbcClient jdbcClient;

    public MovieRepository(JdbcClient jdbcClient) {
        this.jdbcClient = jdbcClient;
    }

    public List<Movie> findAll(Integer userId) {
        return jdbcClient.sql("SELECT * FROM movie WHERE user_id = :userId")
                .param("userId", userId)
                .query(Movie.class)
                .list();
    }

    public Optional<Movie> findById(Integer id, Integer userId) {
        return jdbcClient.sql("SELECT * FROM movie WHERE id = :id AND user_id = :userId")
                .param("id", id)
                .param("userId", userId)
                .query(Movie.class)
                .optional();
    }

    /** Inserts the movie and returns it with the id generated by the database. */
    public Movie create(Movie movie) {
        Integer id = jdbcClient.sql("""
                        INSERT INTO movie (title, rating, review, release_year, user_id)
                        VALUES (:title, :rating, :review, :releaseYear, :userId)
                        RETURNING id
                        """)
                .param("title", movie.title())
                .param("rating", movie.rating())
                .param("review", movie.review())
                .param("releaseYear", movie.releaseYear())
                .param("userId", movie.userId())
                .query(Integer.class)
                .single();
        return new Movie(id, movie.title(), movie.rating(), movie.review(), movie.releaseYear(), movie.userId());
    }

    /** @return the updated movie, or empty if no movie with this id belongs to the user */
    public Optional<Movie> update(Integer id, Movie movie, Integer userId) {
        return jdbcClient.sql("""
                        UPDATE movie
                        SET title = :title, rating = :rating, review = :review, release_year = :releaseYear
                        WHERE id = :id AND user_id = :userId
                        RETURNING *
                        """)
                .param("title", movie.title())
                .param("rating", movie.rating())
                .param("review", movie.review())
                .param("releaseYear", movie.releaseYear())
                .param("id", id)
                .param("userId", userId)
                .query(Movie.class)
                .optional();
    }

    /** @return the number of deleted rows (0 or 1) */
    public int delete(Integer id, Integer userId) {
        return jdbcClient.sql("DELETE FROM movie WHERE id = :id AND user_id = :userId")
                .param("id", id)
                .param("userId", userId)
                .update();
    }
}
