package com.example.moviejournal.movie;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.BDDMockito.given;
import static org.mockito.Mockito.verify;

@ExtendWith(MockitoExtension.class)
class MovieServiceTest {

    private static final Integer USER_ID = 1;
    private static final Integer OTHER_USER_ID = 2;

    @Mock
    private MovieRepository movieRepository;

    @InjectMocks
    private MovieService movieService;

    private final Movie inception = new Movie(10, "Inception", 9, "Masterpiece", 2010, USER_ID);
    private final MovieRequest request = new MovieRequest("Inception", 9, "Masterpiece", 2010);

    @Test
    void findById_returnsMovie_whenItBelongsToUser() {
        given(movieRepository.findById(10, USER_ID)).willReturn(Optional.of(inception));

        MovieResponse result = movieService.findById(10, USER_ID);

        assertThat(result).isEqualTo(new MovieResponse(10, "Inception", 9, "Masterpiece", 2010));
    }

    @Test
    void findById_throwsNotFound_whenMovieDoesNotExist() {
        given(movieRepository.findById(99, USER_ID)).willReturn(Optional.empty());

        assertThatThrownBy(() -> movieService.findById(99, USER_ID))
                .isInstanceOf(MovieNotFoundException.class)
                .hasMessageContaining("99");
    }

    @Test
    void findById_throwsNotFound_whenMovieBelongsToAnotherUser() {
        // The repository filters by user id, so for another user the owner's movie is simply not found.
        given(movieRepository.findById(10, OTHER_USER_ID)).willReturn(Optional.empty());

        assertThatThrownBy(() -> movieService.findById(10, OTHER_USER_ID))
                .isInstanceOf(MovieNotFoundException.class);
        verify(movieRepository).findById(10, OTHER_USER_ID);
    }

    @Test
    void create_savesMovieForCurrentUser_withoutClientId() {
        given(movieRepository.create(any())).willReturn(inception);

        movieService.create(request, USER_ID);

        ArgumentCaptor<Movie> captor = ArgumentCaptor.forClass(Movie.class);
        verify(movieRepository).create(captor.capture());
        Movie saved = captor.getValue();
        assertThat(saved.userId()).isEqualTo(USER_ID);
        assertThat(saved.id()).isNull(); // generated by the database
        assertThat(saved.title()).isEqualTo("Inception");
    }

    @Test
    void update_throwsNotFound_whenMovieDoesNotExist() {
        given(movieRepository.update(any(), any(), any())).willReturn(Optional.empty());

        assertThatThrownBy(() -> movieService.update(99, request, USER_ID))
                .isInstanceOf(MovieNotFoundException.class);
    }

    @Test
    void delete_throwsNotFound_whenNothingWasDeleted() {
        given(movieRepository.delete(99, USER_ID)).willReturn(0);

        assertThatThrownBy(() -> movieService.delete(99, USER_ID))
                .isInstanceOf(MovieNotFoundException.class);
    }

    @Test
    void delete_succeeds_whenOneRowWasDeleted() {
        given(movieRepository.delete(10, USER_ID)).willReturn(1);

        movieService.delete(10, USER_ID);

        verify(movieRepository).delete(10, USER_ID);
    }

    @Test
    void findAll_computesOffsetAndTotalPages() {
        given(movieRepository.findPage(USER_ID, null, "title", "asc", 10, 20L)).willReturn(List.of(inception));
        given(movieRepository.count(USER_ID, null)).willReturn(21L);

        PageResponse<MovieResponse> page = movieService.findAll(USER_ID, 2, 10, "title", "asc", null);

        assertThat(page.content()).hasSize(1);
        assertThat(page.totalElements()).isEqualTo(21);
        assertThat(page.totalPages()).isEqualTo(3); // 21 / 10, rounded up
    }
}
